# ============================================================
# CLASSIFICATION
# ============================================================

def classify_condition(
    temperature,
    vibration,
    current,
    sound
):

    if (
        vibration > CRITICAL_VIB
        or
        current > CRITICAL_CUR
    ):

        return "FAULT"

    if (
        temperature > TEMP_LIMIT
        or
        vibration > VIB_LIMIT
        or
        current > CUR_LIMIT
        or
        sound > SOUND_LIMIT
    ):

        return "DISTURBED"

    return "HEALTHY"


# ============================================================
# PREPROCESSING
# ============================================================

def preprocess_data(
    temperature,
    vibration,
    current,
    sound
):

    start = time.perf_counter()

    if np is not None:

        features = np.array([
            temperature / MAX_TEMP,
            vibration / MAX_VIB,
            current / MAX_CUR,
            sound / MAX_SOUND
        ], dtype=np.float32)

    else:

        features = [
            temperature / MAX_TEMP,
            vibration / MAX_VIB,
            current / MAX_CUR,
            sound / MAX_SOUND
        ]

    elapsed = (
        time.perf_counter()
        -
        start
    ) * 1000

    return features, elapsed


# ============================================================
# MODEL INFERENCE
# ============================================================

def run_model(
    features,
    temperature,
    vibration,
    current,
    sound
):

    start = time.perf_counter()

    prediction = classify_condition(
        temperature,
        vibration,
        current,
        sound
    )

    if prediction == "HEALTHY":

        confidence = 0.97

    elif prediction == "DISTURBED":

        confidence = 0.92

    else:

        confidence = 0.95

    elapsed = (
        time.perf_counter()
        -
        start
    ) * 1000

    return (
        prediction,
        confidence,
        elapsed
    )


# ============================================================
# MAINTENANCE DECISION
# ============================================================

def maintenance_decision(
    temperature,
    vibration,
    current,
    sound
):

    global cumulative_reward

    severity = 0

    if temperature > TEMP_LIMIT:
        severity += 1

    if vibration > VIB_LIMIT:
        severity += 1

    if current > CUR_LIMIT:
        severity += 1

    if sound > SOUND_LIMIT:
        severity += 1

    if (
        vibration > CRITICAL_VIB
        or
        current > CRITICAL_CUR
    ):

        action = "PREVENTIVE MAINTENANCE"
        reward = 2.0

    elif severity >= 2:

        action = "SCHEDULE INSPECTION"
        reward = 1.0

    else:

        action = "CONTINUE OPERATION"
        reward = 0.5

    cumulative_reward += reward

    return action


