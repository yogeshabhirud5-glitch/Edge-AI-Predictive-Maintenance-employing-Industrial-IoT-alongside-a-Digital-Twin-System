def get_system_usage():

    if psutil is None:

        return (
            0.0,
            0.0
        )

    try:

        cpu = psutil.cpu_percent(
            interval=None
        )

        ram = psutil.virtual_memory().percent

        return (
            cpu,
            ram
        )

    except Exception:

        return (
            0.0,
            0.0
        )


