# ============================================================
# RMSE
# ============================================================

def calculate_rmse(errors):

    if len(errors) == 0:
        return 0.0

    total = 0.0

    for error in errors:
        total += error ** 2

    return math.sqrt(
        total / len(errors)
    )


# ============================================================
# MAE
# ============================================================

def calculate_mae(errors):

    if len(errors) == 0:
        return 0.0

    total = 0.0

    for error in errors:
        total += abs(error)

    return total / len(errors)


# ============================================================
# AVERAGE
# ============================================================

def calculate_average(values):

    if len(values) == 0:
        return 0.0

    return sum(values) / len(values)


# ============================================================
# PERCENTILE
# ============================================================

def calculate_percentile(values, percentile):

    if len(values) == 0:
        return 0.0

    if np is not None:

        return float(
            np.percentile(
                values,
                percentile
            )
        )

    values = sorted(values)

    index = int(
        (len(values) - 1)
        *
        percentile
        /
        100
    )

    return values[index]


